export function normalizeClass(text: string): string {
  if (!text) return '';
  return text
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ال/g, '')
    .replace(/-/g, '')
    .replace(/\s+/g, '')
    .trim();
}

export function getFormalClassName(rawClass: string): string {
  if (!rawClass) return '';
  let text = rawClass.trim();
  text = text.replace(/-/g, ' ').replace(/\s+/g, ' ');
  if (text.includes('اول متوسط')) text = text.replace('اول متوسط', 'الأول المتوسط');
  if (text.includes('ثاني متوسط')) text = text.replace('ثاني متوسط', 'الثاني المتوسط');
  if (text.includes('ثالث متوسط')) text = text.replace('ثالث متوسط', 'الثالث المتوسط');
  if (text.endsWith(' ا')) text = text.slice(0, -2) + ' أ';
  if (text.endsWith(' ب')) text = text.slice(0, -2) + ' ب';
  if (text.endsWith(' ج')) text = text.slice(0, -2) + ' ج';
  if (text.endsWith(' د')) text = text.slice(0, -2) + ' د';
  if (text.endsWith(' هـ') || text.endsWith(' ه')) text = text.replace(/\s+هـ?$/, ' هـ');
  return text;
}

